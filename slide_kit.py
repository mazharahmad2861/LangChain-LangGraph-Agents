
from pptx import Presentation
from pptx.util import Inches, Pt
from pptx.dml.color import RGBColor
from pptx.enum.shapes import MSO_SHAPE
from pptx.enum.text import PP_ALIGN


# =====================================================
# BRAND COLORS
# =====================================================

NAVY = RGBColor(20, 37, 63)
TEAL = RGBColor(0, 150, 136)
WHITE = RGBColor(255, 255, 255)
LIGHT_GREY = RGBColor(245, 247, 250)
DARK_GREY = RGBColor(65, 75, 90)


# =====================================================
# TEXT HELPER
# =====================================================

def add_text(
    slide,
    text,
    x,
    y,
    width,
    height,
    font_size=18,
    color=DARK_GREY,
    bold=False
):

    textbox = slide.shapes.add_textbox(
        Inches(x),
        Inches(y),
        Inches(width),
        Inches(height)
    )

    text_frame = textbox.text_frame
    text_frame.word_wrap = True

    paragraph = text_frame.paragraphs[0]
    paragraph.text = text
    paragraph.font.size = Pt(font_size)
    paragraph.font.bold = bold
    paragraph.font.color.rgb = color

    return textbox


# =====================================================
# RECTANGLE HELPER
# =====================================================

def add_rectangle(slide, x, y, width, height, color):

    shape = slide.shapes.add_shape(
        MSO_SHAPE.RECTANGLE,
        Inches(x),
        Inches(y),
        Inches(width),
        Inches(height)
    )

    shape.fill.solid()
    shape.fill.fore_color.rgb = color
    shape.line.fill.background()

    return shape


# =====================================================
# BUILD POWERPOINT
# =====================================================

def build_slide(
    title,
    key_points,
    recommendation,
    output_path
):

    prs = Presentation()

    # 16:9 layout
    prs.slide_width = Inches(13.33)
    prs.slide_height = Inches(7.5)

    slide = prs.slides.add_slide(
        prs.slide_layouts[6]
    )

    # Background
    slide.background.fill.solid()
    slide.background.fill.fore_color.rgb = WHITE

    # Header
    add_rectangle(
        slide,
        0, 0,
        13.33, 1.4,
        NAVY
    )

    add_text(
        slide,
        "AI RESEARCH INSIGHTS",
        0.6, 0.25,
        5, 0.3,
        font_size=12,
        color=TEAL,
        bold=True
    )

    add_text(
        slide,
        title,
        0.6, 0.7,
        12, 0.5,
        font_size=25,
        color=WHITE,
        bold=True
    )

    # Findings heading
    add_text(
        slide,
        "KEY FINDINGS",
        0.7, 1.8,
        5, 0.4,
        font_size=18,
        color=NAVY,
        bold=True
    )

    # Findings
    y_position = 2.4

    for point in key_points[:5]:

        add_rectangle(
            slide,
            0.8,
            y_position + 0.1,
            0.12,
            0.12,
            TEAL
        )

        add_text(
            slide,
            point,
            1.1,
            y_position,
            11.3,
            0.6,
            font_size=16,
            color=DARK_GREY
        )

        y_position += 0.65

    # Recommendation section
    add_rectangle(
        slide,
        0.7, 5.9,
        11.9, 0.9,
        LIGHT_GREY
    )

    add_text(
        slide,
        "KEY TAKEAWAY",
        0.95, 6.05,
        3, 0.25,
        font_size=12,
        color=TEAL,
        bold=True
    )

    add_text(
        slide,
        recommendation,
        0.95, 6.35,
        11.2, 0.35,
        font_size=15,
        color=NAVY,
        bold=True
    )

    # Footer
    add_text(
        slide,
        "Generated by AI Research Assistant",
        8.5, 7.05,
        4.2, 0.2,
        font_size=9,
        color=DARK_GREY
    )

    # Save presentation
    prs.save(output_path)

    return output_path
